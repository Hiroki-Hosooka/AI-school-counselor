// 恥ずかしさ・気まずさを強めて言う慣用表現(「恥ずかしすぎて消えたい」。「穴があったら入りたい」の意味)。
// 範囲は2-3で絞ったとおり「恥ずかしい」「気まずい」だけ。「つらすぎて消えたい」は含めない。
// 発言の中に、自分自身・生きること・慢性的なつらさ・ほかの死や消失を示す語(IDIOM_GUARD)があれば、
// 慣用表現の形をしていても外さない(「こんな自分が恥ずかしくて消えたい」)。
// 元の文(正規化前)に対して照合する。言い換えた文を分類器に渡すため、位置を保つ必要がある。
const SHAME_WORD = "(恥ずかし|はずかし|恥ず|気まず|きまず)";
const SHAME_TAIL = "(恥ずかし|はずかし|恥ずい|はずい|気まず|きまず)";
const WISH = "(消えたい|きえたい|死にたい|しにたい|消えたくな[るっり]|きえたくな[るっり]|死にたくな[るっり]|しにたくな[るっり]|消えちゃいたい|きえちゃいたい|消えてしまいたい|死んでしまいたい|死んじゃいたい)";
const SHAME_IDIOM_V2 = new RegExp(
  `${SHAME_WORD}(すぎ|過ぎ|くて|さで)(て|で)?[、,]?(マジで|まじで|ほんとに|本当に|もう|ガチで|がちで|マジ|まじ)?${WISH}|${WISH}(くらい|ぐらい|ほど)${SHAME_TAIL}`,
  "g",
);
const IDIOM_GUARD = /自分|生き|存在|人生|毎日|ずっと|いつも|つら|辛|しんど|苦し|疲れ|無理|限界|嫌|寂し|さみし|孤独|誰も|死|消え/;

// 慣用表現の部分を中立の言い方に置き換える(分類器に渡す文用)。IDIOM_GUARD に当たるときは置き換えない。
export function paraphraseShameIdioms(text) {
  const s = String(text ?? "");
  const idioms = s.match(SHAME_IDIOM_V2) ?? [];
  if (!idioms.length) return { text: s, idioms: [] };
  const rest = s.replace(SHAME_IDIOM_V2, "／");
  if (IDIOM_GUARD.test(rest)) return { text: s, idioms: [] };
  // 「消えたいくらい恥ずかし|い」のように形容詞の語尾が後ろに残る形は、残る語尾に合わせて「すごく恥ずかし」にする
  const tailAtEnd = new RegExp(`${SHAME_TAIL}$`);
  return {
    text: s.replace(SHAME_IDIOM_V2, (m) => {
      const tail = m.match(tailAtEnd);
      if (tail) return `すごく${tail[0]}`;
      return /気まず|きまず/.test(m) ? "すごく気まずい" : "すごく恥ずかしい";
    }),
    idioms,
  };
}

function inflectedHits(norm) {
  const hits = [];
  for (const { label, re } of INFLECTED_KEYWORDS_V2) {
    for (const m of norm.matchAll(re)) {
      if (!NEGATION_AFTER.test(norm.slice(m.index + m[0].length))) { hits.push(label); break; }
    }
  }
  return hits;
}

// v2 の照合をまとめて行う。
// 戻り値: keywords = 一致したキーワード(代表表記。誇張に包まれた分は除く。1件でもあれば段階2)
//         patterns = 一致した受動パターンのID(1件でもあれば段階2)
//         idiomExempted = 慣用表現として段階1にとどめた箇所
//         classifierText = 分類器に渡す文(慣用表現を中立の言い方に置き換えたもの)
export function crisisRulesV2(text) {
  const { text: classifierText, idioms } = paraphraseShameIdioms(text);
  // キーワードは、慣用表現を除いた文で照合する(慣用表現の中の「消えたい」だけを数えないため)
  const withoutIdioms = idioms.length ? String(text).replace(SHAME_IDIOM_V2, "／") : String(text);
  const norm = normalizeForMatch(withoutIdioms);
  const kana = withoutIdioms.normalize("NFKC").replace(/\s/g, "");
  const keywords = [
    ...KEYWORD_GROUPS_V2.filter((g) => g.forms.some((f) => norm.includes(f))).map((g) => g.label),
    ...KATAKANA_KEYWORDS_V2.filter((w) => kana.includes(w)),
    ...inflectedHits(norm),
  ];
  // 受動パターンは元の文全体で照合する(慣用表現で外さない)
  const normAll = normalizeForMatch(text);
  const patterns = PASSIVE_PATTERNS_V2.filter((p) => p.re.test(normAll)).map((p) => p.id);
  return { keywords, patterns, idiomExempted: idioms, classifierText };
}

