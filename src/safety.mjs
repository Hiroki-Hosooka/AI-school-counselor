// 照合用に文字をそろえる。半角→全角(NFKC)、カタカナ→ひらがな、空白・伸ばし棒・波線・中点・点を除く。
// キーワード・パターンの照合にだけ使い、分類器には元の文を渡す。
export function normalizeForMatch(text) {
  return String(text ?? "")
    .normalize("NFKC")
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[\sー〜~・…‥.]/g, "")
    .toLowerCase();
}

