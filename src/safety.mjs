// ----------------------------------------------------------------------------
// キーワード事前検知(src/classify.mjs の classify() と scripts/test-output-check.mjs が共有する)。
//
// 恥ずかしさ・気まずさを強めて言う慣用表現(「恥ずかしすぎて消えたい」「消えたいくらい恥ずかしい」。
// 「穴があったら入りたい」の意味)の中の「消えたい」「死にたい」だけは、キーワード一致として数えない
// (2026年9月・2-3。ペルソナ回帰テストB5で「恥ずかしすぎて消えたい」が3回中3回、キーワード一致
// だけでTier A(固定応答)になった)。数えないだけで、判定そのものは分類器(CLASSIFIER_PROMPT)に委ねる。
// 分類器が crisis と判定すれば、従来どおりTier Aになる。
//
// 対象は意図的に狭くしている。「つらすぎて消えたい」「死にたいくらい苦しい」のような、
// つらさ・疲れ・孤独と結びついた形は、誇張に見えても本当の希死念慮でありうるため対象外
// (従来どおりキーワード一致で即座にTier A)。さらに、発言の中に自分自身・生きること・慢性的な
// つらさ・ほかの死や消失を示す語(IDIOM_GUARD)が一つでもあれば、慣用表現の形をしていても
// 除外しない(「こんな自分が恥ずかしくて消えたい」は自分の存在への恥であり、慣用表現ではない)。
// この対象を広げる場合は、必ずテスト1(保留セット docs/test-sets/crisis-detection-holdout.json を
// 含む)を再実行し、Tier Aの見逃しが0件のままであることを確認すること。
// ----------------------------------------------------------------------------
const SHAME_IDIOM =
  /(恥ずかし|はずかし|気まず|きまず)(すぎ|過ぎ|くて|さで)(て|で)?[、,]?(マジで|まじで|ほんとに|本当に|もう|ガチで|がちで|マジ|まじ)?(消えたい|きえたい|死にたい|しにたい)|(消えたい|きえたい|死にたい|しにたい)(くらい|ぐらい|ほど)(恥ずかし|はずかし|気まず|きまず)/g;
const IDIOM_GUARD = /自分|生き|存在|人生|毎日|ずっと|いつも|つら|辛|しんど|苦し|疲れ|無理|限界|嫌|寂し|さみし|孤独|誰も|死|消え/;

// 戻り値: keywords = 一致したCRISIS_WORDS(従来どおりの意味。1件でもあればTier A扱い)
//         idiomExempted = 慣用表現として数えなかった箇所(記録用。管理画面・テストのログで確認するため)
export function crisisKeywordHits(text) {
  const idioms = text.match(SHAME_IDIOM) ?? [];
  let masked = text;
  let idiomExempted = [];
  if (idioms.length) {
    const rest = text.replace(SHAME_IDIOM, "／");
    if (!IDIOM_GUARD.test(rest)) {
      masked = rest;
      idiomExempted = idioms;
    }
  }
  return { keywords: CRISIS_WORDS.filter((w) => masked.includes(w)), idiomExempted };
}

